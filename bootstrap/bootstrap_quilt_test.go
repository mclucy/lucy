const (
	quiltTestMinecraft     = "1.21.1"
	quiltTestLoaderVersion = "0.27.1"
	quiltTestLoaderPath    = "libraries/org/quiltmc/quilt-loader/0.27.1/quilt-loader-0.27.1.jar"
	quiltTestShim          = "quilt-server-launch.jar"
	quiltTestLauncherProps = "quilt-server-launcher.properties"
	quiltTestEmbeddedProps = "quilt-server-launch.properties"
	quiltTestManifestEntry = "META-INF/MANIFEST.MF"

	quiltTestLauncherMainClass = "org.quiltmc.loader.impl.launch.server.QuiltServerLauncher"
	quiltTestKnotServerClass   = "org.quiltmc.loader.impl.launch.knot.KnotServer"
)

// quiltTestLibraries mirrors the library layout of a Quilt Meta server profile,
// in the order the profile declares it. The generated Class-Path must follow
// this locked order after the loader itself.
var quiltTestLibraries = []string{
	"libraries/org/quiltmc/quilt-json5/1.0.4/quilt-json5-1.0.4.jar",
	"libraries/org/quiltmc/quilt-config/0.2.2/quilt-config-0.2.2.jar",
	"libraries/org/quiltmc/hashed/1.21.1/hashed-1.21.1.jar",
	"libraries/net/fabricmc/intermediary/1.21.1/intermediary-1.21.1.jar",
	"libraries/net/fabricmc/sponge-mixin/0.15.4+mixin.0.8.7/sponge-mixin-0.15.4+mixin.0.8.7.jar",
	"libraries/org/ow2/asm/asm/9.7.1/asm-9.7.1.jar",
}

// quiltTestTree is a server tree generated by PrepareLocked for a Quilt lock,
// together with the classpath the lock declares.
type quiltTestTree struct {
	root      string
	locked    document.LockedServer
	classpath []string
}

// TestQuiltLauncherGeneration pins the files the Quilt bootstrap writes: the
// loader copy, the launcher manifest (main class and wrapped Class-Path), the
// embedded KnotServer launch property, and the serverJar selector. It also
// proves the unmodified tree is accepted by both verification paths.
func TestQuiltLauncherGeneration(t *testing.T) {
	t.Parallel()
	tree := newQuiltTestTree(t)

	loaderData, err := os.ReadFile(filepath.Join(tree.root, filepath.FromSlash(quiltTestLoaderPath)))
	if err != nil {
		t.Fatalf("reading generated loader: %v", err)
	}
	if string(loaderData) != quiltTestLoaderJar {
		t.Fatalf("generated loader bytes = %q, want locked loader bytes", loaderData)
	}
	if _, err := os.Stat(filepath.Join(tree.root, "run.sh")); !os.IsNotExist(err) {
		t.Fatalf("Quilt bootstrap wrote run.sh, want launcher JAR only: %v", err)
	}

	launcherData, err := os.ReadFile(filepath.Join(tree.root, quiltTestLauncherProps))
	if err != nil {
		t.Fatalf("reading launcher properties: %v", err)
	}
	if string(launcherData) != "serverJar=server.jar\n" {
		t.Fatalf("quilt-server-launcher.properties = %q, want serverJar=server.jar", launcherData)
	}

	entries := quiltReadJar(t, filepath.Join(tree.root, quiltTestShim))
	var names []string
	for name := range entries {
		names = append(names, name)
	}
	slices.Sort(names)
	if !slices.Equal(names, []string{quiltTestManifestEntry, quiltTestEmbeddedProps}) {
		t.Fatalf("launcher JAR entries = %v, want manifest and launch properties only", names)
	}

	manifest := string(entries[quiltTestManifestEntry])
	attributes := quiltManifestAttributes(manifest)
	if got := attributes["Main-Class"]; got != quiltTestLauncherMainClass {
		t.Fatalf("manifest Main-Class = %q, want %q", got, quiltTestLauncherMainClass)
	}
	if got, want := strings.Fields(attributes["Class-Path"]), tree.classpath; !slices.Equal(got, want) {
		t.Fatalf("manifest Class-Path = %v, want %v", got, want)
	}
	if want := quiltLauncherManifest(quiltTestLauncherMainClass, tree.classpath); normalizeTestNewlines(manifest) != normalizeTestNewlines(want) {
		t.Fatalf("manifest bytes = %q, want %q", manifest, want)
	}

	if got := strings.TrimSpace(string(entries[quiltTestEmbeddedProps])); got != "launch.mainClass="+quiltTestKnotServerClass {
		t.Fatalf("embedded launch properties = %q, want Quilt KnotServer main class", got)
	}

	launch := bootstrap.LaunchFor(server.BootstrapMethodQuilt)
	if launch.Command != "java -jar quilt-server-launch.jar nogui" {
		t.Fatalf("Quilt launch command = %q, want launcher JAR invocation", launch.Command)
	}
	if launch.Handler != "vanilla_handler" {
		t.Fatalf("Quilt launch handler = %q, want vanilla_handler", launch.Handler)
	}

	outputs, err := bootstrap.ValidateStagedOutputs(tree.root, tree.locked)
	if err != nil {
		t.Fatalf("validate generated Quilt tree: %v", err)
	}
	for _, rel := range []string{
		"server.jar",
		quiltTestLoaderPath,
		quiltTestShim,
		quiltTestLauncherProps,
	} {
		if !quiltHasServerPath(outputs, rel) {
			t.Fatalf("verified outputs omit %s: %v", rel, outputs)
		}
	}

	existing, err := bootstrap.CheckExisting(tree.root, tree.locked)
	if err != nil {
		t.Fatalf("check generated Quilt tree: %v", err)
	}
	if !existing.Current || existing.Status != bootstrap.CurrentnessCurrent {
		t.Fatalf("generated tree status = %s current=%t, want current: %s", existing.Status, existing.Current, existing.Reason)
	}
}

// TestQuiltLauncherRejectsMalformedTree proves that the launcher verifier reads
// the generated files and rejects each broken Java contract, from a foreign
// main class through a misplaced loader layout.
func TestQuiltLauncherRejectsMalformedTree(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name   string
		mutate func(t *testing.T, tree quiltTestTree)
	}{
		{
			name: "foreign launcher main class",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltMutateLauncherManifest(t, tree, func() []byte {
					return []byte(quiltLauncherManifest(
						"net.fabricmc.loader.impl.launch.server.FabricServerLauncher",
						tree.classpath,
					))
				})
			},
		},
		{
			name: "manifest without class path",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltMutateLauncherManifest(t, tree, func() []byte {
					return []byte("Manifest-Version: 1.0\nMain-Class: " + quiltTestLauncherMainClass + "\n")
				})
			},
		},
		{
			name: "class path drops loader",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltMutateLauncherManifest(t, tree, func() []byte {
					return []byte(quiltLauncherManifest(quiltTestLauncherMainClass, tree.classpath[1:]))
				})
			},
		},
		{
			name: "class path drops library",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltMutateLauncherManifest(t, tree, func() []byte {
					return []byte(quiltLauncherManifest(quiltTestLauncherMainClass, tree.classpath[:len(tree.classpath)-1]))
				})
			},
		},
		{
			name: "class path reorders libraries",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltMutateLauncherManifest(t, tree, func() []byte {
					reordered := slices.Clone(tree.classpath)
					reordered[1], reordered[len(reordered)-1] = reordered[len(reordered)-1], reordered[1]
					return []byte(quiltLauncherManifest(quiltTestLauncherMainClass, reordered))
				})
			},
		},
		{
			name: "embedded KnotServer property is Fabric",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltUpdateLauncherJar(t, tree, func(entries map[string][]byte) {
					entries[quiltTestEmbeddedProps] = []byte("launch.mainClass=net.fabricmc.loader.impl.launch.knot.KnotServer\n")
				})
			},
		},
		{
			name: "embedded KnotServer property missing",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltUpdateLauncherJar(t, tree, func(entries map[string][]byte) {
					delete(entries, quiltTestEmbeddedProps)
				})
			},
		},
		{
			name: "serverJar property points elsewhere",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltWriteFile(t, filepath.Join(tree.root, quiltTestLauncherProps), "serverJar=server-quilt.jar\n")
			},
		},
		{
			name: "serverJar property missing",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltRemoveFile(t, filepath.Join(tree.root, quiltTestLauncherProps))
			},
		},
		{
			name: "launcher JAR carries an extra entry",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltUpdateLauncherJar(t, tree, func(entries map[string][]byte) {
					entries["org/quiltmc/loader/impl/launch/server/QuiltServerLauncher.class"] = []byte("launcher class")
				})
			},
		},
		{
			name: "launcher JAR repeats a manifest entry",
			mutate: func(t *testing.T, tree quiltTestTree) {
				path := filepath.Join(tree.root, quiltTestShim)
				entries := quiltReadJar(t, path)
				quiltWriteFile(t, path, string(quiltZipEntries(t, []quiltZipEntry{
					{name: quiltTestManifestEntry, data: entries[quiltTestManifestEntry]},
					{name: quiltTestEmbeddedProps, data: entries[quiltTestEmbeddedProps]},
					{name: quiltTestManifestEntry, data: entries[quiltTestManifestEntry]},
				})))
			},
		},
		{
			name: "launcher JAR is not a ZIP",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltWriteFile(t, filepath.Join(tree.root, quiltTestShim), "not a launcher JAR")
			},
		},
		{
			name: "launcher JAR missing",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltRemoveFile(t, filepath.Join(tree.root, quiltTestShim))
			},
		},
		{
			name: "loader missing from locked library path",
			mutate: func(t *testing.T, tree quiltTestTree) {
				quiltRemoveFile(t, filepath.Join(tree.root, filepath.FromSlash(quiltTestLoaderPath)))
			},
		},
		{
			name: "loader written to a different version path",
			mutate: func(t *testing.T, tree quiltTestTree) {
				oldPath := filepath.Join(tree.root, filepath.FromSlash(quiltTestLoaderPath))
				newRel := "libraries/org/quiltmc/quilt-loader/0.26.0/quilt-loader-0.26.0.jar"
				newPath := filepath.Join(tree.root, filepath.FromSlash(newRel))
				if err := os.MkdirAll(filepath.Dir(newPath), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.Rename(oldPath, newPath); err != nil {
					t.Fatal(err)
				}
			},
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			tree := newQuiltTestTree(t)
			tc.mutate(t, tree)

			existing, err := bootstrap.CheckExisting(tree.root, tree.locked)
			if err != nil {
				t.Fatalf("check malformed tree: %v", err)
			}
			if existing.Current || existing.Status != bootstrap.CurrentnessMismatch {
				t.Fatalf("malformed tree status = %s current=%t, want mismatch: %s", existing.Status, existing.Current, existing.Reason)
			}
			if _, err := bootstrap.ValidateStagedOutputs(tree.root, tree.locked); err == nil {
				t.Fatal("staged validation accepted malformed Quilt launcher tree")
			}
		})
	}
}

// newQuiltTestTree prepares a complete Quilt server tree through the public
// bootstrap entry point, using a loader core artifact and a Quilt Meta-shaped
// library set with real 1.21.1 / 0.27.1 coordinates.
func newQuiltTestTree(t *testing.T) quiltTestTree {
	t.Helper()
	stage := t.TempDir()
	source := t.TempDir()

	corePath := filepath.Join(source, "quilt-loader-"+quiltTestLoaderVersion+".jar")
	quiltWriteFile(t, corePath, quiltTestLoaderJar)

	sources := map[string]string{}
	inputs := []server.BootstrapInput{
		{
			Path: "server.jar",
			Artifact: catalog.Artifact{
				Version:  version.Version(quiltTestMinecraft),
				Filename: "server.jar",
				Hashes:   map[string]string{"sha256": quiltTestSHA256([]byte(quiltTestMinecraftServerJar))},
			},
		},
	}
	serverJarPath := filepath.Join(source, "server.jar")
	quiltWriteFile(t, serverJarPath, quiltTestMinecraftServerJar)
	sources["server.jar"] = serverJarPath

	for _, lib := range quiltTestLibraries {
		data := []byte("quilt library: " + lib)
		libPath := filepath.Join(source, strings.NewReplacer("/", "_", "+", "_").Replace(lib))
		quiltWriteFile(t, libPath, string(data))
		sources[lib] = libPath
		inputs = append(inputs, server.BootstrapInput{
			Path: lib,
			Artifact: catalog.Artifact{
				Version:  version.Version(quiltTestMinecraft),
				Filename: filepath.Base(lib),
				Hashes:   map[string]string{"sha256": quiltTestSHA256(data)},
			},
		})
	}

	locked := document.LockedServer{
		Directory:   ".",
		Minecraft:   version.Version(quiltTestMinecraft),
		Product:     server.Product("quilt"),
		CoreVersion: version.Version(quiltTestLoaderVersion),
		Artifact: catalog.Artifact{
			ProjectID: "quilt-loader",
			Version:   version.Version(quiltTestLoaderVersion),
			Filename:  "quilt-loader-" + quiltTestLoaderVersion + ".jar",
			Hashes:    map[string]string{"sha256": quiltTestSHA256([]byte(quiltTestLoaderJar))},
		},
		Bootstrapper: server.BootstrapMethodQuilt,
		Inputs:       inputs,
	}

	if err := bootstrap.PrepareLocked(
		t.Context(), stage, locked, corePath, sources, "", io.Discard,
	); err != nil {
		t.Fatalf("prepare Quilt tree: %v", err)
	}

	return quiltTestTree{
		root:      stage,
		locked:    locked,
		classpath: append([]string{quiltTestLoaderPath}, quiltTestLibraries...),
	}
}

// quiltTestLoaderJar stands in for the locked org.quiltmc:quilt-loader artifact.
const quiltTestLoaderJar = "PK\x03\x04 quilt-loader-0.27.1"

// quiltTestMinecraftServerJar stands in for the locked vanilla server.jar.
const quiltTestMinecraftServerJar = "vanilla server 1.21.1"

// quiltLauncherManifest returns the manifest the Quilt adapter must write.
func quiltLauncherManifest(mainClass string, classpath []string) string {
	return "Manifest-Version: 1.0\nMain-Class: " + mainClass + "\n" +
		quiltWrapLongLine("Class-Path: "+strings.Join(classpath, " "), 70) + "\n"
}

// quiltWrapLongLine mirrors the JAR manifest continuation rule the adapter
// applies: split at the 70-byte boundary and continue with a leading space.
func quiltWrapLongLine(line string, width int) string {
	if len(line) <= width {
		return line
	}
	var builder strings.Builder
	for len(line) > width {
		builder.WriteString(line[:width])
		builder.WriteByte('\n')
		builder.WriteByte(' ')
		line = line[width:]
	}
	builder.WriteString(line)
	return builder.String()
}

// quiltManifestAttributes parses manifest main attributes, joining wrapped
// continuation lines before trimming the assembled value.
func quiltManifestAttributes(manifest string) map[string]string {
	raw := make(map[string]string)
	var key string
	for line := range strings.SplitSeq(normalizeTestNewlines(manifest), "\n") {
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, " ") {
			if key != "" {
				raw[key] += line[1:]
			}
			continue
		}
		name, value, ok := strings.Cut(line, ":")
		if !ok {
			continue
		}
		key = name
		raw[key] = value
	}
	attributes := make(map[string]string, len(raw))
	for name, value := range raw {
		attributes[name] = strings.TrimSpace(value)
	}
	return attributes
}

func normalizeTestNewlines(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\r\n", "\n"), "\r", "\n")
}

func quiltMutateLauncherManifest(t *testing.T, tree quiltTestTree, manifest func() []byte) {
	t.Helper()
	quiltUpdateLauncherJar(t, tree, func(entries map[string][]byte) {
		entries[quiltTestManifestEntry] = manifest()
	})
}

// quiltUpdateLauncherJar rewrites the generated launcher JAR through the given
// mutation while keeping every unmodified entry.
func quiltUpdateLauncherJar(t *testing.T, tree quiltTestTree, mutate func(map[string][]byte)) {
	t.Helper()
	path := filepath.Join(tree.root, quiltTestShim)
	entries := quiltReadJar(t, path)
	mutate(entries)
	quiltWriteJar(t, path, entries)
}

func quiltReadJar(t *testing.T, path string) map[string][]byte {
	t.Helper()
	reader, err := zip.OpenReader(path)
	if err != nil {
		t.Fatalf("open JAR %s: %v", path, err)
	}
	defer reader.Close()
	entries := make(map[string][]byte, len(reader.File))
	for _, file := range reader.File {
		rc, err := file.Open()
		if err != nil {
			t.Fatalf("open entry %s: %v", file.Name, err)
		}
		data, err := io.ReadAll(rc)
		if closeErr := rc.Close(); err == nil {
			err = closeErr
		}
		if err != nil {
			t.Fatalf("read entry %s: %v", file.Name, err)
		}
		entries[file.Name] = data
	}
	return entries
}

func quiltWriteJar(t *testing.T, path string, entries map[string][]byte) {
	t.Helper()
	quiltWriteFile(t, path, string(quiltZipBytes(t, entries)))
}

func quiltZipBytes(t *testing.T, entries map[string][]byte) []byte {
	t.Helper()
	var ordered []quiltZipEntry
	for _, name := range slices.Sorted(maps.Keys(entries)) {
		ordered = append(ordered, quiltZipEntry{name: name, data: entries[name]})
	}
	return quiltZipEntries(t, ordered)
}

// quiltZipEntry is one ordered JAR entry. A slice, unlike a map, can carry a
// duplicate name.
type quiltZipEntry struct {
	name string
	data []byte
}

func quiltZipEntries(t *testing.T, entries []quiltZipEntry) []byte {
	t.Helper()
	var buf bytes.Buffer
	writer := zip.NewWriter(&buf)
	for _, entry := range entries {
		file, err := writer.Create(entry.name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := file.Write(entry.data); err != nil {
			t.Fatal(err)
		}
	}
	if err := writer.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func quiltWriteFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func quiltRemoveFile(t *testing.T, path string) {
	t.Helper()
	if err := os.Remove(path); err != nil {
		t.Fatal(err)
	}
}

func quiltTestSHA256(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func quiltHasServerPath(outputs []bootstrap.Output, rel string) bool {
	return slices.ContainsFunc(outputs, func(out bootstrap.Output) bool {
		return out.ServerPath == rel
	})
}
