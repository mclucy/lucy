// OutputPolicy defines the lifecycle and ownership of an output file.
type OutputPolicy = string

const (
	// PolicyManaged designates outputs that Lucy owns, manages, and protects
	// against local user modifications.
	PolicyManaged OutputPolicy = "managed"
	// PolicySeed designates output files initialized only when missing;
	// subsequent content is user-owned and never clobbered or pruned.
	PolicySeed OutputPolicy = "seed"
	// PolicyDiscard designates outputs generated in staging for execution
	// purposes that must never be committed to the workspace runtime.
	PolicyDiscard OutputPolicy = "discard"
)

// MaterialRole defines the operational purpose of input or staging material.
type MaterialRole = string

const (
	// RoleRuntime designates material intended for runtime execution.
	RoleRuntime MaterialRole = "runtime"
	// RoleBootstrapOnly designates material required only during installation
	// or bootstrap execution, not to be retained in runtime output.
	RoleBootstrapOnly MaterialRole = "bootstrap-only"
)

// OutputOrigin indicates whether an output is generated by the bootstrap adapter
// or supplied as a locked input.
type OutputOrigin = string

const (
	// OriginGenerated designates outputs generated or extracted by bootstrap execution.
	OriginGenerated OutputOrigin = "generated"
	// OriginInput designates inputs supplied from locked artifacts.
	OriginInput OutputOrigin = "input"
)

// OutputSpec describes a declared exact output path or bounded directory scope.
type OutputSpec struct {
	// Path is the server-relative exact path (if exact).
	Path string
	// Scope is the server-relative bounded directory prefix (if dynamic).
	Scope string
	// Policy is the ownership policy for matching files.
	Policy OutputPolicy
	// Role is the material role for matching files.
	Role MaterialRole
	// Origin indicates whether the path originates from a locked input or generated output.
	Origin OutputOrigin
}

// Output describes a concrete staged or verified output file.
type Output struct {
	// Path is the workspace-relative path (e.g. "server.jar" or "server/server.jar").
	Path string
	// ServerPath is the server-relative path (e.g. "server.jar").
	ServerPath string
	// SHA256 is the hexadecimal SHA-256 digest of the file contents.
	SHA256 string
	// Mode is the file permission bits.
	Mode uint32
	// Policy is the ownership policy (managed, seed, discard).
	Policy OutputPolicy
	// Role is the material role (runtime, bootstrap-only).
	Role MaterialRole
}

// CurrentnessStatus indicates whether an existing server tree satisfies the locked bootstrap contract.
type CurrentnessStatus string

const (
	// CurrentnessCurrent indicates all required outputs exist, launcher semantics match,
	// and all locked artifact hashes match.
	CurrentnessCurrent CurrentnessStatus = "current"
	// CurrentnessInconclusive indicates the existing tree cannot be proven to satisfy
	// the locked contract without executing bootstrap.
	CurrentnessInconclusive CurrentnessStatus = "inconclusive"
	// CurrentnessMismatch indicates a missing required output or artifact hash mismatch.
	CurrentnessMismatch CurrentnessStatus = "mismatch"
)

// CheckResult reports the outcome of verifying an existing tree against a locked server.
type CheckResult struct {
	Current bool
	Status  CurrentnessStatus
	Reason  string
	Outputs []Output
}

// validateContract checks the locked server's bootstrap method, locked inputs, and declared outputs.
// It detects and rejects:
// - Unsupported bootstrap adapters.
// - Collisions where a locked input claims an exact path that the method generates (e.g. Fabric input run.sh).
// - Collisions where multiple locked inputs claim the same destination.
// - Overlaps where an exact input or output conflicts with a scope policy (e.g. Forge input in .bootstrap-data/ claiming managed).
// - Overlaps between scopes with conflicting policies or roles.
func validateContract(locked document.LockedServer) (map[string]OutputSpec, []OutputSpec, error) {
	var generated []OutputSpec
	var scopes []OutputSpec

	switch locked.Bootstrapper {
	case serverpkg.BootstrapMethodPlain:
		generated = []OutputSpec{
			{Path: "server.jar", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
		}
	case serverpkg.BootstrapMethodPaperclip:
		generated = []OutputSpec{
			{Path: "server.jar", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
		}
		scopes = []OutputSpec{
			{Scope: "versions/", Policy: PolicyManaged, Role: RoleRuntime},
			{Scope: "libraries/", Policy: PolicyManaged, Role: RoleRuntime},
			{Scope: "cache/", Policy: PolicyManaged, Role: RoleRuntime},
		}
	case serverpkg.BootstrapMethodFabric:
		loaderPath, err := fabricLoaderPath(locked.CoreVersion.String())
		if err != nil {
			return nil, nil, fmt.Errorf("resolving Fabric loader path: %w", err)
		}
		generated = []OutputSpec{
			{Path: "run.sh", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "run.bat", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "fabric-server-launch.jar", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "fabric-server-launcher.properties", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: loaderPath, Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
		}
		scopes = []OutputSpec{
			{Scope: "libraries/", Policy: PolicyManaged, Role: RoleRuntime},
		}
	case serverpkg.BootstrapMethodForgeInstaller:
		generated = []OutputSpec{
			{Path: "run.sh", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "run.bat", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "user_jvm_args.txt", Policy: PolicySeed, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "README.txt", Policy: PolicySeed, Role: RoleRuntime, Origin: OriginGenerated},
		}
		scopes = []OutputSpec{
			{Scope: ".bootstrap-data/", Policy: PolicyDiscard, Role: RoleBootstrapOnly},
			{Scope: "libraries/", Policy: PolicyManaged, Role: RoleRuntime},
		}
	default:
		return nil, nil, fmt.Errorf("unsupported bootstrap adapter %q", locked.Bootstrapper)
	}

	// Normalize scopes
	for i := range scopes {
		sc := filepath.ToSlash(filepath.Clean(scopes[i].Scope))
		if !strings.HasSuffix(sc, "/") {
			sc += "/"
		}
		scopes[i].Scope = sc
	}

	genMap := make(map[string]OutputSpec, len(generated))
	for _, gen := range generated {
		clean := filepath.ToSlash(filepath.Clean(gen.Path))
		gen.Path = clean
		genMap[clean] = gen
	}

	exact := make(map[string]OutputSpec, len(generated)+len(locked.Inputs))
	for k, v := range genMap {
		exact[k] = v
	}

	seenInputs := make(map[string]bool, len(locked.Inputs))
	for _, input := range locked.Inputs {
		if err := document.SafeRelativePath(input.Path); err != nil {
			return nil, nil, fmt.Errorf("unsafe locked input path %q: %w", input.Path, err)
		}
		clean := filepath.ToSlash(filepath.Clean(input.Path))
		if seenInputs[clean] {
			return nil, nil, fmt.Errorf("duplicate locked input destination %q", clean)
		}
		seenInputs[clean] = true

		// Check collision with generated output: independent origin collision must fail even if same policy
		if gen, ok := genMap[clean]; ok {
			return nil, nil, fmt.Errorf("collision between locked input and generated bootstrap output claiming %q (input policy %s vs generated policy %s)", clean, PolicyManaged, gen.Policy)
		}

		policy := PolicyManaged
		role := RoleRuntime

		if locked.Bootstrapper == serverpkg.BootstrapMethodForgeInstaller {
			if isForgeDiscardInput(clean) {
				policy = PolicyDiscard
				role = RoleBootstrapOnly
			}
		}

		// Validate input against scope rules: input cannot conflict with scope policy
		for _, sc := range scopes {
			if strings.HasPrefix(clean, sc.Scope) {
				if policy != sc.Policy || role != sc.Role {
					return nil, nil, fmt.Errorf("locked input %q (%s/%s) conflicts with bootstrap scope %q (%s/%s)", clean, policy, role, sc.Scope, sc.Policy, sc.Role)
				}
			}
		}

		exact[clean] = OutputSpec{
			Path:   clean,
			Policy: policy,
			Role:   role,
			Origin: OriginInput,
		}
	}

	// Validate generated outputs against scopes
	for _, gen := range genMap {
		for _, sc := range scopes {
			if strings.HasPrefix(gen.Path, sc.Scope) {
				if gen.Policy != sc.Policy || gen.Role != sc.Role {
					return nil, nil, fmt.Errorf("generated output %q (%s/%s) conflicts with bootstrap scope %q (%s/%s)", gen.Path, gen.Policy, gen.Role, sc.Scope, sc.Policy, sc.Role)
				}
			}
		}
	}

	// Validate overlapping scopes
	for i := range scopes {
		for j := i + 1; j < len(scopes); j++ {
			s1 := scopes[i]
			s2 := scopes[j]
			if strings.HasPrefix(s1.Scope, s2.Scope) || strings.HasPrefix(s2.Scope, s1.Scope) {
				if s1.Policy != s2.Policy || s1.Role != s2.Role {
					return nil, nil, fmt.Errorf("conflicting overlapping bootstrap scopes: %q (%s/%s) vs %q (%s/%s)", s1.Scope, s1.Policy, s1.Role, s2.Scope, s2.Policy, s2.Role)
				}
			}
		}
	}

	return exact, scopes, nil
}

// OutputSpecs reports the declared output paths and bounded scopes of a locked server.
func OutputSpecs(locked document.LockedServer) []OutputSpec {
	exact, scopes, err := validateContract(locked)
	if err != nil {
		return nil
	}
	specs := make([]OutputSpec, 0, len(exact)+len(scopes))
	for _, spec := range exact {
		specs = append(specs, spec)
	}
	for _, sc := range scopes {
		specs = append(specs, sc)
	}
	slices.SortFunc(specs, func(a, b OutputSpec) int {
		if a.Path != "" && b.Path != "" {
			return strings.Compare(a.Path, b.Path)
		}
		if a.Path != "" {
			return -1
		}
		if b.Path != "" {
			return 1
		}
		return strings.Compare(a.Scope, b.Scope)
	})
	return specs
}

// ValidateStagedOutputs inspects the staged server tree under stageRoot/locked.Directory.
// It verifies that:
// - All paths are safe relative paths within the server directory without symlink or FIFO escapes.
// - All locked inputs and runtime core artifacts match their expected hashes.
// - Every file falls within the method's declared exact paths or bounded scopes.
// - No collisions exist between output policies or origins.
// - Method launcher semantics match.
// Discard and bootstrap-only files (e.g. Forge .bootstrap-data/, server-mappings.txt) are preserved in the result
// with PolicyDiscard / RoleBootstrapOnly so callers omit them from committed runtime receipts.
func ValidateStagedOutputs(stageRoot string, locked document.LockedServer) ([]Output, error) {
	exact, scopes, err := validateContract(locked)
	if err != nil {
		return nil, fmt.Errorf("invalid bootstrap output contract: %w", err)
	}

	if err := checkPathSafety(stageRoot, locked.Directory, false); err != nil {
		return nil, fmt.Errorf("unsafe server directory %q: %w", locked.Directory, err)
	}
	serverRoot := filepath.Join(stageRoot, locked.Directory)
	if _, err := os.Stat(serverRoot); err != nil {
		return nil, fmt.Errorf("staged server directory does not exist: %w", err)
	}

	var outputs []Output
	seen := make(map[string]bool)
	cachedDigests := make(map[string]string)

	err = filepath.WalkDir(serverRoot, func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if p == serverRoot {
			return nil
		}
		rel, err := filepath.Rel(serverRoot, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(filepath.Clean(rel))

		if d.IsDir() {
			return nil
		}

		if err := checkPathSafety(serverRoot, rel, true); err != nil {
			return err
		}

		if seen[rel] {
			return fmt.Errorf("duplicate staged output: %s", rel)
		}
		seen[rel] = true

		var policy OutputPolicy
		var role MaterialRole

		if spec, ok := exact[rel]; ok {
			policy = spec.Policy
			role = spec.Role
		} else {
			matchedScope := false
			for _, sc := range scopes {
				if strings.HasPrefix(rel, sc.Scope) {
					policy = sc.Policy
					role = sc.Role
					matchedScope = true
					break
				}
			}
			if !matchedScope {
				return fmt.Errorf("unpermitted output file %q outside declared bootstrap scope", rel)
			}
		}

		f, err := os.Open(p)
		if err != nil {
			return err
		}
		hasher := sha256.New()
		if _, err := io.Copy(hasher, f); err != nil {
			f.Close()
			return err
		}
		f.Close()
		digest := hex.EncodeToString(hasher.Sum(nil))
		cachedDigests[rel] = digest

		info, err := d.Info()
		if err != nil {
			return err
		}

		wsPath := rel
		if locked.Directory != "" && locked.Directory != "." {
			wsPath = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, rel)))
		}

		outputs = append(outputs, Output{
			Path:       wsPath,
			ServerPath: rel,
			SHA256:     digest,
			Mode:       uint32(info.Mode().Perm()),
			Policy:     policy,
			Role:       role,
		})
		return nil
	})
	if err != nil {
		return nil, err
	}

	// Shared method verification for staging: verify required outputs, pinned hashes, and launcher semantics.
	// cachedDigests avoids re-reading and re-hashing all files from disk a second time.
	verification, err := verifyServerTree(serverRoot, locked, true, cachedDigests)
	if err != nil {
		return nil, fmt.Errorf("staged bootstrap verification error: %w", err)
	}
	if !verification.Current {
		return nil, fmt.Errorf("staged bootstrap output failed verification: %s", verification.Reason)
	}

	slices.SortFunc(outputs, func(a, b Output) int {
		return strings.Compare(a.Path, b.Path)
	})
	return outputs, nil
}

// InspectStage is an alias for ValidateStagedOutputs.
func InspectStage(stageRoot string, locked document.LockedServer) ([]Output, error) {
	return ValidateStagedOutputs(stageRoot, locked)
}

// CheckExisting checks whether an existing server directory already satisfies the locked bootstrap contract
// without executing bootstrap.
// It shares the single verification path with stage validation, verifying:
// - Exact presence and hashes of all locked inputs and runtime core artifacts (for Forge, the core installer is bootstrap-only).
// - Semantics and classpath of generated launch files.
// - Embedded metadata (download-context, versions.list, patches.list, libraries.list) for Paperclip.
// For methods where outputs are generated dynamically and cannot be proven identical to lock artifacts
// without execution (such as Forge installer processors), CheckExisting returns
// CurrentnessInconclusive and Current=false. Inconclusive must never be reported as success.
// When verification is inconclusive but not conflicting, verified attributable outputs are returned
// in Outputs so adoption can preserve them without claiming full bootstrap currentness.
// Definite conflicts and hash mismatches return CurrentnessMismatch.
func CheckExisting(serverDir string, locked document.LockedServer) (CheckResult, error) {
	if _, _, err := validateContract(locked); err != nil {
		return CheckResult{
			Current: false,
			Status:  CurrentnessMismatch,
			Reason:  fmt.Sprintf("invalid bootstrap contract: %v", err),
		}, err
	}
	return verifyServerTree(serverDir, locked, false, nil)
}

func verifyServerTree(serverDir string, locked document.LockedServer, isStaging bool, cachedDigests map[string]string) (CheckResult, error) {
	if err := checkPathSafety(serverDir, "", false); err != nil {
		return CheckResult{
			Current: false,
			Status:  CurrentnessMismatch,
			Reason:  fmt.Sprintf("unsafe server directory: %v", err),
		}, err
	}

	info, err := os.Stat(serverDir)
	if err != nil {
		if os.IsNotExist(err) {
			return CheckResult{
				Current: false,
				Status:  CurrentnessMismatch,
				Reason:  "server directory does not exist",
			}, nil
		}
		return CheckResult{
			Current: false,
			Status:  CurrentnessMismatch,
			Reason:  err.Error(),
		}, err
	}
	if !info.IsDir() {
		return CheckResult{
			Current: false,
			Status:  CurrentnessMismatch,
			Reason:  "server path is not a directory",
		}, nil
	}

	seenOutputs := make(map[string]bool)
	var outputs []Output
	addOutput := func(out Output) {
		if !seenOutputs[out.ServerPath] {
			seenOutputs[out.ServerPath] = true
			outputs = append(outputs, out)
		}
	}

	switch locked.Bootstrapper {
	case serverpkg.BootstrapMethodPlain:
		failed := false
		reason := ""

		if err := checkPathSafety(serverDir, "server.jar", true); err != nil {
			failed = true
			reason = fmt.Sprintf("server.jar safety: %v", err)
		} else {
			serverJarPath := filepath.Join(serverDir, "server.jar")
			st, err := os.Lstat(serverJarPath)
			if err != nil || !st.Mode().IsRegular() {
				failed = true
				reason = "missing or irregular server.jar"
			} else {
				sha256Hex, err := verifyArtifactHashes(serverJarPath, locked.Artifact.Hashes, cachedDigests["server.jar"])
				if err != nil {
					failed = true
					reason = fmt.Sprintf("server.jar hash verification: %v", err)
				} else {
					wsPath := "server.jar"
					if locked.Directory != "" && locked.Directory != "." {
						wsPath = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, "server.jar")))
					}
					addOutput(Output{
						Path:       wsPath,
						ServerPath: "server.jar",
						SHA256:     sha256Hex,
						Mode:       uint32(st.Mode().Perm()),
						Policy:     PolicyManaged,
						Role:       RoleRuntime,
					})
				}
			}
		}

		for _, input := range locked.Inputs {
			if err := document.SafeRelativePath(input.Path); err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("unsafe locked input path %q: %v", input.Path, err)
				}
				continue
			}
			cleanRel := filepath.ToSlash(filepath.Clean(input.Path))
			if err := checkPathSafety(serverDir, cleanRel, true); err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("input %s safety: %v", cleanRel, err)
				}
				continue
			}
			fullPath := filepath.Join(serverDir, filepath.FromSlash(cleanRel))
			st, err := os.Lstat(fullPath)
			if err != nil || !st.Mode().IsRegular() {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("missing input %s", cleanRel)
				}
				continue
			}
			inSHA256, err := verifyArtifactHashes(fullPath, input.Artifact.Hashes, cachedDigests[cleanRel])
			if err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("input %s hash mismatch: %v", cleanRel, err)
				}
				continue
			}
			wsInPath := cleanRel
			if locked.Directory != "" && locked.Directory != "." {
				wsInPath = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, cleanRel)))
			}
			addOutput(Output{
				Path:       wsInPath,
				ServerPath: cleanRel,
				SHA256:     inSHA256,
				Mode:       uint32(st.Mode().Perm()),
				Policy:     PolicyManaged,
				Role:       RoleRuntime,
			})
		}

		slices.SortFunc(outputs, func(a, b Output) int {
			return strings.Compare(a.Path, b.Path)
		})

		if failed {
			return CheckResult{
				Current: false,
				Status:  CurrentnessMismatch,
				Reason:  reason,
				Outputs: outputs,
			}, nil
		}

		return CheckResult{
			Current: true,
			Status:  CurrentnessCurrent,
			Outputs: outputs,
		}, nil

	case serverpkg.BootstrapMethodPaperclip:
		failed := false
		reason := ""

		serverJarPath := filepath.Join(serverDir, "server.jar")
		if err := checkPathSafety(serverDir, "server.jar", true); err != nil {
			failed = true
			reason = fmt.Sprintf("server.jar safety: %v", err)
		} else {
			st, err := os.Lstat(serverJarPath)
			if err != nil || !st.Mode().IsRegular() {
				failed = true
				reason = "missing or irregular server.jar"
			} else {
				serverSHA256, err := verifyArtifactHashes(serverJarPath, locked.Artifact.Hashes, cachedDigests["server.jar"])
				if err != nil {
					failed = true
					reason = fmt.Sprintf("server.jar hash verification: %v", err)
				} else {
					wsServerJar := "server.jar"
					if locked.Directory != "" && locked.Directory != "." {
						wsServerJar = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, "server.jar")))
					}
					addOutput(Output{
						Path:       wsServerJar,
						ServerPath: "server.jar",
						SHA256:     serverSHA256,
						Mode:       uint32(st.Mode().Perm()),
						Policy:     PolicyManaged,
						Role:       RoleRuntime,
					})
				}
			}
		}

		for _, input := range locked.Inputs {
			if err := document.SafeRelativePath(input.Path); err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("unsafe locked input path %q: %v", input.Path, err)
				}
				continue
			}
			cleanRel := filepath.ToSlash(filepath.Clean(input.Path))
			if err := checkPathSafety(serverDir, cleanRel, true); err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("input %s safety: %v", cleanRel, err)
				}
				continue
			}
			fullPath := filepath.Join(serverDir, filepath.FromSlash(cleanRel))
			st, err := os.Lstat(fullPath)
			if err != nil || !st.Mode().IsRegular() {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("missing input %s", cleanRel)
				}
				continue
			}
			inSHA256, err := verifyArtifactHashes(fullPath, input.Artifact.Hashes, cachedDigests[cleanRel])
			if err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("input %s hash mismatch: %v", cleanRel, err)
				}
				continue
			}
			wsInPath := cleanRel
			if locked.Directory != "" && locked.Directory != "." {
				wsInPath = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, cleanRel)))
			}
			addOutput(Output{
				Path:       wsInPath,
				ServerPath: cleanRel,
				SHA256:     inSHA256,
				Mode:       uint32(st.Mode().Perm()),
				Policy:     PolicyManaged,
				Role:       RoleRuntime,
			})
		}

		if !failed {
			zr, err := zip.OpenReader(serverJarPath)
			if err != nil {
				failed = true
				reason = fmt.Sprintf("opening Paperclip server.jar: %v", err)
			} else {
				defer zr.Close()

				// 1. download-context
				dlBytes, err := readZipEntry(&zr.Reader, "META-INF/download-context")
				if err != nil {
					failed = true
					reason = "missing download-context in Paperclip jar"
				} else {
					dlParts := strings.Fields(string(dlBytes))
					if len(dlParts) != 3 {
						failed = true
						reason = "malformed download-context"
					} else {
						cacheFileName := dlParts[2]
						cacheExpectedSHA256 := dlParts[0]
						cacheRel, err := scopedPath("cache", cacheFileName)
						if err != nil {
							failed = true
							reason = fmt.Sprintf("download-context scope safety: %v", err)
						} else if err := checkPathSafety(serverDir, cacheRel, true); err != nil {
							failed = true
							reason = err.Error()
						} else {
							cacheFullPath := filepath.Join(serverDir, filepath.FromSlash(cacheRel))
							cst, err := os.Lstat(cacheFullPath)
							if err != nil || !cst.Mode().IsRegular() {
								failed = true
								reason = fmt.Sprintf("missing Paperclip cache file %s", cacheRel)
							} else {
								cacheSHA256 := cachedDigests[cacheRel]
								if cacheSHA256 == "" {
									cacheSHA256, _, err = fileDigests(cacheFullPath, true, false)
								}
								if err != nil || !strings.EqualFold(cacheSHA256, cacheExpectedSHA256) {
									failed = true
									reason = fmt.Sprintf("Paperclip cache file %s SHA256 mismatch", cacheRel)
								} else {
									wsCache := cacheRel
									if locked.Directory != "" && locked.Directory != "." {
										wsCache = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, cacheRel)))
									}
									addOutput(Output{
										Path:       wsCache,
										ServerPath: cacheRel,
										SHA256:     cacheSHA256,
										Mode:       uint32(cst.Mode().Perm()),
										Policy:     PolicyManaged,
										Role:       RoleRuntime,
									})
								}
							}
						}
					}
				}

				// 2. versions.list (required)
				verBytes, err := readZipEntry(&zr.Reader, "META-INF/versions.list")
				if err != nil {
					failed = true
					if reason == "" {
						reason = "missing META-INF/versions.list in Paperclip jar"
					}
				} else {
					scanner := bufio.NewScanner(bytes.NewReader(verBytes))
					for scanner.Scan() {
						line := strings.TrimSpace(scanner.Text())
						if line == "" || strings.HasPrefix(line, "#") {
							continue
						}
						parts := strings.Split(line, "\t")
						if len(parts) != 3 {
							failed = true
							if reason == "" {
								reason = fmt.Sprintf("malformed line in versions.list: %q", line)
							}
							break
						}
						verExpectedHash := parts[0]
						verRel, err := scopedPath("versions", parts[2])
						if err != nil {
							failed = true
							if reason == "" {
								reason = fmt.Sprintf("versions.list path safety: %v", err)
							}
							break
						}
						if err := checkPathSafety(serverDir, verRel, true); err != nil {
							failed = true
							if reason == "" {
								reason = err.Error()
							}
							continue
						}
						verFullPath := filepath.Join(serverDir, filepath.FromSlash(verRel))
						vst, err := os.Lstat(verFullPath)
						if err != nil || !vst.Mode().IsRegular() {
							failed = true
							if reason == "" {
								reason = fmt.Sprintf("missing Paperclip version output %s", verRel)
							}
							continue
						}
						verActualHash := cachedDigests[verRel]
						if verActualHash == "" {
							verActualHash, _, err = fileDigests(verFullPath, true, false)
						}
						if err != nil || !strings.EqualFold(verActualHash, verExpectedHash) {
							failed = true
							if reason == "" {
								reason = fmt.Sprintf("Paperclip version file %s SHA256 mismatch", verRel)
							}
							continue
						}
						wsVer := verRel
						if locked.Directory != "" && locked.Directory != "." {
							wsVer = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, verRel)))
						}
						addOutput(Output{
							Path:       wsVer,
							ServerPath: verRel,
							SHA256:     verActualHash,
							Mode:       uint32(vst.Mode().Perm()),
							Policy:     PolicyManaged,
							Role:       RoleRuntime,
						})
					}
					if err := scanner.Err(); err != nil && !failed {
						failed = true
						if reason == "" {
							reason = fmt.Sprintf("reading versions.list: %v", err)
						}
					}
				}

				// 3. patches.list (if present)
				patchedPaths := make(map[string]bool)
				patchBytes, err := readZipEntry(&zr.Reader, "META-INF/patches.list")
				if err == nil {
					scanner := bufio.NewScanner(bytes.NewReader(patchBytes))
					for scanner.Scan() {
						line := strings.TrimSpace(scanner.Text())
						if line == "" || strings.HasPrefix(line, "#") {
							continue
						}
						parts := strings.Split(line, "\t")
						if len(parts) != 7 {
							failed = true
							if reason == "" {
								reason = fmt.Sprintf("malformed line in patches.list: %q", line)
							}
							break
						}
						location := parts[0]
						if location != "versions" && location != "libraries" {
							failed = true
							if reason == "" {
								reason = fmt.Sprintf("invalid patch location %q in patches.list (must be versions or libraries)", location)
							}
							break
						}
						outputHash := parts[3]
						outputPath := parts[6]
						outRel, err := scopedPath(location, outputPath)
						if err != nil {
							failed = true
							if reason == "" {
								reason = fmt.Sprintf("patches.list path safety: %v", err)
							}
							break
						}
						patchedPaths[outRel] = true
						if err := checkPathSafety(serverDir, outRel, true); err != nil {
							failed = true
							if reason == "" {
								reason = err.Error()
							}
							continue
						}
						outFullPath := filepath.Join(serverDir, filepath.FromSlash(outRel))
						ost, err := os.Lstat(outFullPath)
						if err != nil || !ost.Mode().IsRegular() {
							failed = true
							if reason == "" {
								reason = fmt.Sprintf("missing Paperclip patched output %s", outRel)
							}
							continue
						}
						outActualHash := cachedDigests[outRel]
						if outActualHash == "" {
							outActualHash, _, err = fileDigests(outFullPath, true, false)
						}
						if err != nil || !strings.EqualFold(outActualHash, outputHash) {
							failed = true
							if reason == "" {
								reason = fmt.Sprintf("Paperclip patched output %s SHA256 mismatch", outRel)
							}
							continue
						}
						wsOut := outRel
						if locked.Directory != "" && locked.Directory != "." {
							wsOut = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, outRel)))
						}
						addOutput(Output{
							Path:       wsOut,
							ServerPath: outRel,
							SHA256:     outActualHash,
							Mode:       uint32(ost.Mode().Perm()),
							Policy:     PolicyManaged,
							Role:       RoleRuntime,
						})
					}
					if err := scanner.Err(); err != nil && !failed {
						failed = true
						if reason == "" {
							reason = fmt.Sprintf("reading patches.list: %v", err)
						}
					}
				}

				// 4. libraries.list
				// If earlier checks failed, fail immediately with CurrentnessMismatch
				if failed {
					slices.SortFunc(outputs, func(a, b Output) int {
						return strings.Compare(a.Path, b.Path)
					})
					return CheckResult{
						Current: false,
						Status:  CurrentnessMismatch,
						Reason:  reason,
						Outputs: outputs,
					}, nil
				}

				libBytes, err := readZipEntry(&zr.Reader, "META-INF/libraries.list")
				if err != nil {
					slices.SortFunc(outputs, func(a, b Output) int {
						return strings.Compare(a.Path, b.Path)
					})
					return CheckResult{
						Current: false,
						Status:  CurrentnessInconclusive,
						Reason:  "missing META-INF/libraries.list in Paperclip jar",
						Outputs: outputs,
					}, nil
				}
				scanner := bufio.NewScanner(bytes.NewReader(libBytes))
				for scanner.Scan() {
					line := strings.TrimSpace(scanner.Text())
					if line == "" || strings.HasPrefix(line, "#") {
						continue
					}
					parts := strings.Split(line, "\t")
					if len(parts) != 3 {
						failed = true
						if reason == "" {
							reason = fmt.Sprintf("malformed line in libraries.list: %q", line)
						}
						break
					}
					libExpectedHash := parts[0]
					libRel, err := scopedPath("libraries", parts[2])
					if err != nil {
						failed = true
						if reason == "" {
							reason = fmt.Sprintf("libraries.list path safety: %v", err)
						}
						break
					}
					// If file was generated/replaced by patches.list, skip verifying unpatched hash
					if patchedPaths[libRel] {
						continue
					}
					if err := checkPathSafety(serverDir, libRel, true); err != nil {
						failed = true
						if reason == "" {
							reason = err.Error()
						}
						continue
					}
					libFullPath := filepath.Join(serverDir, filepath.FromSlash(libRel))
					lst, err := os.Lstat(libFullPath)
					if err != nil || !lst.Mode().IsRegular() {
						failed = true
						if reason == "" {
							reason = fmt.Sprintf("missing Paperclip library output %s", libRel)
						}
						continue
					}
					libActualHash := cachedDigests[libRel]
					if libActualHash == "" {
						libActualHash, _, err = fileDigests(libFullPath, true, false)
					}
					if err != nil || !strings.EqualFold(libActualHash, libExpectedHash) {
						failed = true
						if reason == "" {
							reason = fmt.Sprintf("Paperclip library file %s SHA256 mismatch", libRel)
						}
						continue
					}
					wsLib := libRel
					if locked.Directory != "" && locked.Directory != "." {
						wsLib = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, libRel)))
					}
					addOutput(Output{
						Path:       wsLib,
						ServerPath: libRel,
						SHA256:     libActualHash,
						Mode:       uint32(lst.Mode().Perm()),
						Policy:     PolicyManaged,
						Role:       RoleRuntime,
					})
				}
				if err := scanner.Err(); err != nil && !failed {
					failed = true
					if reason == "" {
						reason = fmt.Sprintf("reading libraries.list: %v", err)
					}
				}
			}
		}

		slices.SortFunc(outputs, func(a, b Output) int {
			return strings.Compare(a.Path, b.Path)
		})

		if failed {
			return CheckResult{
				Current: false,
				Status:  CurrentnessMismatch,
				Reason:  reason,
				Outputs: outputs,
			}, nil
		}

		return CheckResult{
			Current: true,
			Status:  CurrentnessCurrent,
			Outputs: outputs,
		}, nil

	case serverpkg.BootstrapMethodFabric:
		failed := false
		reason := ""

		// 1. Verify locked core (Fabric loader) artifact
		loaderRel, err := fabricLoaderPath(locked.CoreVersion.String())
		if err != nil {
			failed = true
			reason = fmt.Sprintf("resolving Fabric loader path: %v", err)
		} else if err := checkPathSafety(serverDir, loaderRel, true); err != nil {
			failed = true
			reason = fmt.Sprintf("loader path safety: %v", err)
		} else {
			loaderPath := filepath.Join(serverDir, filepath.FromSlash(loaderRel))
			st, err := os.Lstat(loaderPath)
			if err != nil || !st.Mode().IsRegular() {
				failed = true
				reason = fmt.Sprintf("missing or irregular Fabric loader jar: %s", loaderRel)
			} else {
				loaderSHA256, err := verifyArtifactHashes(loaderPath, locked.Artifact.Hashes, cachedDigests[loaderRel])
				if err != nil {
					failed = true
					reason = fmt.Sprintf("Fabric loader jar hash verification: %v", err)
				} else {
					wsLoader := loaderRel
					if locked.Directory != "" && locked.Directory != "." {
						wsLoader = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, loaderRel)))
					}
					addOutput(Output{
						Path:       wsLoader,
						ServerPath: loaderRel,
						SHA256:     loaderSHA256,
						Mode:       uint32(st.Mode().Perm()),
						Policy:     PolicyManaged,
						Role:       RoleRuntime,
					})
				}
			}
		}

		// 2. Verify all declared inputs
		for _, input := range locked.Inputs {
			if err := document.SafeRelativePath(input.Path); err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("unsafe locked input path %q: %v", input.Path, err)
				}
				continue
			}
			cleanRel := filepath.ToSlash(filepath.Clean(input.Path))
			if err := checkPathSafety(serverDir, cleanRel, true); err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("input %s safety: %v", cleanRel, err)
				}
				continue
			}
			fullPath := filepath.Join(serverDir, filepath.FromSlash(cleanRel))
			ist, err := os.Lstat(fullPath)
			if err != nil || !ist.Mode().IsRegular() {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("missing or irregular locked input %s", cleanRel)
				}
				continue
			}
			inSHA256, err := verifyArtifactHashes(fullPath, input.Artifact.Hashes, cachedDigests[cleanRel])
			if err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("input %s hash mismatch: %v", cleanRel, err)
				}
				continue
			}
			wsInPath := cleanRel
			if locked.Directory != "" && locked.Directory != "." {
				wsInPath = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, cleanRel)))
			}
			addOutput(Output{
				Path:       wsInPath,
				ServerPath: cleanRel,
				SHA256:     inSHA256,
				Mode:       uint32(ist.Mode().Perm()),
				Policy:     PolicyManaged,
				Role:       RoleRuntime,
			})
		}

		// 3. Verify launcher file semantics (includes required run.bat)
		if err := verifyLauncherSemantics(serverDir, locked); err != nil {
			failed = true
			if reason == "" {
				reason = err.Error()
			}
		} else {
			for _, launchFile := range []string{"run.sh", "run.bat", "fabric-server-launcher.properties", "fabric-server-launch.jar"} {
				if err := checkPathSafety(serverDir, launchFile, true); err != nil {
					failed = true
					if reason == "" {
						reason = err.Error()
					}
					continue
				}
				fPath := filepath.Join(serverDir, launchFile)
				fInfo, err := os.Lstat(fPath)
				if err != nil || !fInfo.Mode().IsRegular() {
					failed = true
					if reason == "" {
						reason = fmt.Sprintf("missing or irregular launch file %s", launchFile)
					}
					continue
				}
				fHash := cachedDigests[launchFile]
				if fHash == "" {
					fHash, _, err = fileDigests(fPath, true, false)
				}
				if err != nil {
					failed = true
					if reason == "" {
						reason = fmt.Sprintf("reading launch file %s: %v", launchFile, err)
					}
					continue
				}
				wsFile := launchFile
				if locked.Directory != "" && locked.Directory != "." {
					wsFile = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, launchFile)))
				}
				addOutput(Output{
					Path:       wsFile,
					ServerPath: launchFile,
					SHA256:     fHash,
					Mode:       uint32(fInfo.Mode().Perm()),
					Policy:     PolicyManaged,
					Role:       RoleRuntime,
				})
			}
		}

		slices.SortFunc(outputs, func(a, b Output) int {
			return strings.Compare(a.Path, b.Path)
		})

		if failed {
			return CheckResult{
				Current: false,
				Status:  CurrentnessMismatch,
				Reason:  reason,
				Outputs: outputs,
			}, nil
		}

		return CheckResult{
			Current: true,
			Status:  CurrentnessCurrent,
			Outputs: outputs,
		}, nil

	case serverpkg.BootstrapMethodForgeInstaller:
		failed := false
		reason := ""

		for _, input := range locked.Inputs {
			if err := document.SafeRelativePath(input.Path); err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("unsafe locked input path %q: %v", input.Path, err)
				}
				continue
			}
			cleanRel := filepath.ToSlash(filepath.Clean(input.Path))
			if err := checkPathSafety(serverDir, cleanRel, true); err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("input %s safety: %v", cleanRel, err)
				}
				continue
			}
			fullPath := filepath.Join(serverDir, filepath.FromSlash(cleanRel))
			ist, err := os.Lstat(fullPath)
			if err != nil || !ist.Mode().IsRegular() {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("missing or irregular locked input %s", cleanRel)
				}
				continue
			}
			inSHA256, err := verifyArtifactHashes(fullPath, input.Artifact.Hashes, cachedDigests[cleanRel])
			if err != nil {
				failed = true
				if reason == "" {
					reason = fmt.Sprintf("input %s hash mismatch: %v", cleanRel, err)
				}
				continue
			}
			wsInPath := cleanRel
			if locked.Directory != "" && locked.Directory != "." {
				wsInPath = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, cleanRel)))
			}
			policy := PolicyManaged
			role := RoleRuntime
			if isForgeDiscardInput(cleanRel) {
				policy = PolicyDiscard
				role = RoleBootstrapOnly
			}
			addOutput(Output{
				Path:       wsInPath,
				ServerPath: cleanRel,
				SHA256:     inSHA256,
				Mode:       uint32(ist.Mode().Perm()),
				Policy:     policy,
				Role:       role,
			})
		}

		// Verify launcher semantics (run.sh, user_jvm_args.txt, unix_args.txt, run.bat/win_args when present)
		if err := verifyLauncherSemantics(serverDir, locked); err != nil {
			failed = true
			if reason == "" {
				reason = err.Error()
			}
		} else {
			runShPath := filepath.Join(serverDir, "run.sh")
			runShInfo, err := os.Lstat(runShPath)
			if err == nil && runShInfo.Mode().IsRegular() {
				runShHash := cachedDigests["run.sh"]
				if runShHash == "" {
					runShHash, _, err = fileDigests(runShPath, true, false)
				}
				if err != nil {
					failed = true
					if reason == "" {
						reason = fmt.Sprintf("reading run.sh: %v", err)
					}
				} else {
					wsRunSh := "run.sh"
					if locked.Directory != "" && locked.Directory != "." {
						wsRunSh = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, wsRunSh)))
					}
					addOutput(Output{
						Path:       wsRunSh,
						ServerPath: "run.sh",
						SHA256:     runShHash,
						Mode:       uint32(runShInfo.Mode().Perm()),
						Policy:     PolicyManaged,
						Role:       RoleRuntime,
					})
				}
			}

			jvmArgsPath := filepath.Join(serverDir, "user_jvm_args.txt")
			jvmInfo, err := os.Lstat(jvmArgsPath)
			if err == nil && jvmInfo.Mode().IsRegular() {
				jvmHash := cachedDigests["user_jvm_args.txt"]
				if jvmHash == "" {
					jvmHash, _, err = fileDigests(jvmArgsPath, true, false)
				}
				if err != nil {
					failed = true
					if reason == "" {
						reason = fmt.Sprintf("reading user_jvm_args.txt: %v", err)
					}
				} else {
					wsJvm := "user_jvm_args.txt"
					if locked.Directory != "" && locked.Directory != "." {
						wsJvm = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, wsJvm)))
					}
					addOutput(Output{
						Path:       wsJvm,
						ServerPath: "user_jvm_args.txt",
						SHA256:     jvmHash,
						Mode:       uint32(jvmInfo.Mode().Perm()),
						Policy:     PolicySeed,
						Role:       RoleRuntime,
					})
				}
			}

			if err := checkPathSafety(serverDir, "run.bat", true); err == nil {
				runBatPath := filepath.Join(serverDir, "run.bat")
				if runBatInfo, err := os.Lstat(runBatPath); err == nil && runBatInfo.Mode().IsRegular() {
					runBatHash := cachedDigests["run.bat"]
					if runBatHash == "" {
						runBatHash, _, err = fileDigests(runBatPath, true, false)
					}
					if err != nil {
						failed = true
						if reason == "" {
							reason = fmt.Sprintf("reading run.bat: %v", err)
						}
					} else {
						wsRunBat := "run.bat"
						if locked.Directory != "" && locked.Directory != "." {
							wsRunBat = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, wsRunBat)))
						}
						addOutput(Output{
							Path:       wsRunBat,
							ServerPath: "run.bat",
							SHA256:     runBatHash,
							Mode:       uint32(runBatInfo.Mode().Perm()),
							Policy:     PolicyManaged,
							Role:       RoleRuntime,
						})
					}
				}
			}

			readmePath := filepath.Join(serverDir, "README.txt")
			if readmeInfo, err := os.Lstat(readmePath); err == nil && readmeInfo.Mode().IsRegular() {
				readmeHash := cachedDigests["README.txt"]
				if readmeHash == "" {
					readmeHash, _, err = fileDigests(readmePath, true, false)
				}
				if err != nil {
					failed = true
					if reason == "" {
						reason = fmt.Sprintf("reading README.txt: %v", err)
					}
				} else {
					wsReadme := "README.txt"
					if locked.Directory != "" && locked.Directory != "." {
						wsReadme = filepath.ToSlash(filepath.Clean(filepath.Join(locked.Directory, wsReadme)))
					}
					addOutput(Output{
						Path:       wsReadme,
						ServerPath: "README.txt",
						SHA256:     readmeHash,
						Mode:       uint32(readmeInfo.Mode().Perm()),
						Policy:     PolicySeed,
						Role:       RoleRuntime,
					})
				}
			}
		}

		slices.SortFunc(outputs, func(a, b Output) int {
			return strings.Compare(a.Path, b.Path)
		})

		// Return Mismatch when evidence definitively conflicts (e.g. input hash mismatch or broken launcher files)
		if failed {
			return CheckResult{
				Current: false,
				Status:  CurrentnessMismatch,
				Reason:  reason,
				Outputs: outputs,
			}, nil
		}

		if isStaging {
			return CheckResult{
				Current: true,
				Status:  CurrentnessCurrent,
				Outputs: outputs,
			}, nil
		}

		// Existing Forge trees: dynamic processor outputs cannot be proven identical to lock artifacts without execution.
		// Outputs retains the verified attributable launcher files and inputs for adoption.
		return CheckResult{
			Current: false,
			Status:  CurrentnessInconclusive,
			Reason:  "Forge installer processor outputs cannot be verified against locked artifact pins without execution",
			Outputs: outputs,
		}, nil

	default:
		return CheckResult{
			Current: false,
			Status:  CurrentnessInconclusive,
			Reason:  fmt.Sprintf("unsupported bootstrap adapter %q", locked.Bootstrapper),
		}, nil
	}
}

// verifyLauncherSemantics checks method-specific launch script and shim JAR semantics.
// This single verification path is shared across post-stage validation and in-place adoption.
func verifyLauncherSemantics(serverDir string, locked document.LockedServer) error {
	switch locked.Bootstrapper {
	case serverpkg.BootstrapMethodPlain, serverpkg.BootstrapMethodPaperclip:
		if err := checkPathSafety(serverDir, "server.jar", true); err != nil {
			return err
		}
		st, err := os.Lstat(filepath.Join(serverDir, "server.jar"))
		if err != nil {
			return errors.New("missing server.jar")
		}
		if !st.Mode().IsRegular() {
			return errors.New("server.jar is not a regular file")
		}
		return nil

	case serverpkg.BootstrapMethodFabric:
		for _, f := range []string{"fabric-server-launcher.properties", "run.sh", "run.bat", "fabric-server-launch.jar"} {
			if err := checkPathSafety(serverDir, f, true); err != nil {
				return err
			}
		}

		propsPath := filepath.Join(serverDir, "fabric-server-launcher.properties")
		propsData, err := readBoundedFile(propsPath, 1<<20)
		if err != nil {
			return fmt.Errorf("reading fabric-server-launcher.properties: %w", err)
		}
		if strings.TrimSpace(string(propsData)) != "serverJar=server.jar" {
			return errors.New("fabric-server-launcher.properties does not match expected serverJar=server.jar")
		}

		loaderPath, err := fabricLoaderPath(locked.CoreVersion.String())
		if err != nil {
			return fmt.Errorf("resolving fabric loader path: %w", err)
		}
		classpath := []string{loaderPath}
		for _, input := range locked.Inputs {
			if strings.HasPrefix(input.Path, "libraries/") {
				classpath = append(classpath, input.Path)
			}
		}
		unixClasspath := strings.Join(classpath, ":")
		windowsClasspath := strings.Join(classpath, ";")

		runShPath := filepath.Join(serverDir, "run.sh")
		runShData, err := readBoundedFile(runShPath, 1<<20)
		if err != nil {
			return fmt.Errorf("reading run.sh: %w", err)
		}
		expectedRunSh := "#!/bin/sh\ncd -- \"$(dirname -- \"$0\")\"\nexec java -cp '" + unixClasspath + "' net.fabricmc.loader.impl.launch.server.FabricServerLauncher nogui \"$@\"\n"
		if normalizeNewlines(string(runShData)) != normalizeNewlines(expectedRunSh) {
			return errors.New("run.sh does not match expected Fabric launch script")
		}

		runBatPath := filepath.Join(serverDir, "run.bat")
		runBatData, err := readBoundedFile(runBatPath, 1<<20)
		if err != nil {
			return fmt.Errorf("reading run.bat: %w", err)
		}
		expectedRunBat := "@echo off\r\ncd /d %~dp0\r\njava -cp \"" + windowsClasspath + "\" net.fabricmc.loader.impl.launch.server.FabricServerLauncher nogui %*\r\n"
		if normalizeNewlines(string(runBatData)) != normalizeNewlines(expectedRunBat) {
			return errors.New("run.bat does not match expected Fabric launch script")
		}

		shimPath := filepath.Join(serverDir, "fabric-server-launch.jar")
		zr, err := zip.OpenReader(shimPath)
		if err != nil {
			return fmt.Errorf("invalid fabric-server-launch.jar: %w", err)
		}
		defer zr.Close()

		manifestBytes, err := readZipEntry(&zr.Reader, "META-INF/MANIFEST.MF")
		if err != nil {
			return errors.New("missing META-INF/MANIFEST.MF in fabric-server-launch.jar")
		}
		expectedManifest := "Manifest-Version: 1.0\nMain-Class: net.fabricmc.loader.impl.launch.server.FabricServerLauncher\n" + wrapLongLine("Class-Path: "+strings.Join(classpath, " "), 70) + "\n"
		if normalizeNewlines(string(manifestBytes)) != normalizeNewlines(expectedManifest) {
			return errors.New("fabric-server-launch.jar manifest does not match expected FabricServerLauncher manifest")
		}

		propBytes, err := readZipEntry(&zr.Reader, "fabric-server-launch.properties")
		if err != nil {
			return errors.New("missing fabric-server-launch.properties in fabric-server-launch.jar")
		}
		if strings.TrimSpace(string(propBytes)) != "launch.mainClass=net.fabricmc.loader.impl.launch.knot.KnotServer" {
			return errors.New("fabric-server-launch.jar properties does not match KnotServer mainClass")
		}
		return nil

	case serverpkg.BootstrapMethodForgeInstaller:
		if err := checkPathSafety(serverDir, "run.sh", true); err != nil {
			return err
		}
		if err := checkPathSafety(serverDir, "user_jvm_args.txt", true); err != nil {
			return err
		}

		argsRel := forgeArgsPath(locked.Product, locked.Minecraft.String(), locked.CoreVersion.String())
		if err := checkPathSafety(serverDir, argsRel, true); err != nil {
			return fmt.Errorf("launch arguments safety: %w", err)
		}
		stArgs, err := os.Lstat(filepath.Join(serverDir, filepath.FromSlash(argsRel)))
		if err != nil || !stArgs.Mode().IsRegular() {
			return fmt.Errorf("missing or irregular Forge launch arguments file %s", argsRel)
		}

		runShPath := filepath.Join(serverDir, "run.sh")
		runShData, err := readBoundedFile(runShPath, 1<<20)
		if err != nil {
			return fmt.Errorf("reading run.sh: %w", err)
		}
		expectedExec := "java @user_jvm_args.txt @" + argsRel + " \"$@\""
		hasExpectedExec := false
		for _, line := range strings.Split(string(runShData), "\n") {
			trimmed := strings.TrimSpace(line)
			trimmed = strings.TrimPrefix(trimmed, "exec ")
			if trimmed == expectedExec {
				hasExpectedExec = true
				break
			}
		}
		if !hasExpectedExec {
			return fmt.Errorf("run.sh does not launch Forge with expected arguments (@user_jvm_args.txt @%s)", argsRel)
		}

		if err := checkPathSafety(serverDir, "run.bat", true); err != nil {
			return err
		}
		runBatPath := filepath.Join(serverDir, "run.bat")
		stBat, err := os.Lstat(runBatPath)
		if err != nil || !stBat.Mode().IsRegular() {
			return errors.New("missing or irregular run.bat")
		}
		runBatData, err := readBoundedFile(runBatPath, 1<<20)
		if err != nil {
			return fmt.Errorf("reading run.bat: %w", err)
		}
		winArgsRel := forgeWinArgsPath(locked.Product, locked.Minecraft.String(), locked.CoreVersion.String())
		if strings.Contains(string(runBatData), winArgsRel) {
			if err := checkPathSafety(serverDir, winArgsRel, true); err != nil {
				return fmt.Errorf("win_args.txt safety: %w", err)
			}
			stWinArgs, err := os.Lstat(filepath.Join(serverDir, filepath.FromSlash(winArgsRel)))
			if err != nil || !stWinArgs.Mode().IsRegular() {
				return fmt.Errorf("missing or irregular Forge launch arguments file %s", winArgsRel)
			}
		} else if !strings.Contains(string(runBatData), argsRel) {
			return fmt.Errorf("run.bat does not reference expected launch arguments (%s or %s)", winArgsRel, argsRel)
		}

		jvmPath := filepath.Join(serverDir, "user_jvm_args.txt")
		if st, err := os.Lstat(jvmPath); err != nil || !st.Mode().IsRegular() {
			return errors.New("missing or irregular user_jvm_args.txt")
		}
		return nil

	default:
		return nil
	}
}

func fabricLoaderPath(version string) (string, error) {
	if version == "" || version == "." || version == ".." || strings.ContainsAny(version, "/\\") {
		return "", fmt.Errorf("invalid Fabric loader version %q", version)
	}
	p, err := maven.Path("net.fabricmc:fabric-loader:" + version)
	if err != nil {
		return "", err
	}
	return filepath.ToSlash(filepath.Join("libraries", p)), nil
}

func forgeArgsPath(product serverpkg.Product, mcVersion, coreVersion string) string {
	prefix := "net/neoforged/neoforge/"
	version := coreVersion
	if product == "forge" {
		prefix = "net/minecraftforge/forge/"
		version = mcVersion + "-" + coreVersion
	}
	return "libraries/" + prefix + version + "/unix_args.txt"
}

func forgeWinArgsPath(product serverpkg.Product, mcVersion, coreVersion string) string {
	prefix := "net/neoforged/neoforge/"
	version := coreVersion
	if product == "forge" {
		prefix = "net/minecraftforge/forge/"
		version = mcVersion + "-" + coreVersion
	}
	return "libraries/" + prefix + version + "/win_args.txt"
}

func isForgeDiscardInput(cleanPath string) bool {
	return cleanPath == "server-mappings.txt" || cleanPath == "server.jar" || strings.HasPrefix(cleanPath, ".bootstrap-data/")
}

func readBoundedFile(path string, maxBytes int64) ([]byte, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	lr := io.LimitReader(f, maxBytes+1)
	data, err := io.ReadAll(lr)
	if err != nil {
		return nil, err
	}
	if int64(len(data)) > maxBytes {
		return nil, fmt.Errorf("file %s exceeds maximum allowed size (%d bytes)", path, maxBytes)
	}
	return data, nil
}

func normalizeNewlines(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\r\n", "\n"), "\r", "\n")
}

func scopedPath(scope, relPath string) (string, error) {
	cleanRel := filepath.Clean(relPath)
	for _, part := range strings.Split(filepath.ToSlash(cleanRel), "/") {
		if part == ".." {
			return "", fmt.Errorf("path %q contains illegal parent directory traversal", relPath)
		}
	}
	if err := document.SafeRelativePath(cleanRel); err != nil {
		return "", fmt.Errorf("unsafe relative path %q: %w", relPath, err)
	}
	cleanScope := filepath.ToSlash(filepath.Clean(scope))
	if !strings.HasSuffix(cleanScope, "/") {
		cleanScope += "/"
	}
	joined := filepath.ToSlash(filepath.Clean(filepath.Join(cleanScope, cleanRel)))
	if !strings.HasPrefix(joined, cleanScope) {
		return "", fmt.Errorf("path %q escapes declared scope %q", relPath, scope)
	}
	return joined, nil
}

func checkPathSafety(root, rel string, checkLeaf bool) error {
	if rel != "" {
		if err := document.SafeRelativePath(rel); err != nil {
			return fmt.Errorf("unsafe relative path %q: %w", rel, err)
		}
	}

	cleanRoot := filepath.Clean(root)
	rootInfo, err := os.Lstat(cleanRoot)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if rootInfo.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("symlink detected in root path: %s", cleanRoot)
	}
	if rootInfo.Mode()&(os.ModeNamedPipe|os.ModeSocket|os.ModeDevice) != 0 {
		return fmt.Errorf("unsupported file type in root path: %s (%v)", cleanRoot, rootInfo.Mode())
	}

	if rel == "" || rel == "." {
		return nil
	}

	cleanRel := filepath.Clean(rel)
	parts := strings.Split(filepath.ToSlash(cleanRel), "/")
	cur := cleanRoot
	for i, part := range parts {
		if part == "." || part == "" {
			continue
		}
		cur = filepath.Join(cur, part)
		info, err := os.Lstat(cur)
		if err != nil {
			if os.IsNotExist(err) {
				return nil
			}
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("symlink detected in path segment %s", cur)
		}
		if info.Mode()&(os.ModeNamedPipe|os.ModeSocket|os.ModeDevice) != 0 {
			return fmt.Errorf("unsupported file type in path %s (%v)", cur, info.Mode())
		}
		if i < len(parts)-1 && !info.IsDir() {
			return fmt.Errorf("path component is not a directory: %s", cur)
		}
		if i == len(parts)-1 && checkLeaf {
			if !info.Mode().IsRegular() {
				return fmt.Errorf("leaf path is not a regular file: %s (%v)", cur, info.Mode())
			}
		}
	}
	return nil
}

func verifyArtifactHashes(path string, expectedHashes map[string]string, cachedSHA256 string) (string, error) {
	if len(expectedHashes) == 0 {
		return "", errors.New("no expected hashes declared in lock")
	}
	exp256 := expectedHashes["sha256"]
	exp1 := expectedHashes["sha1"]
	if exp256 == "" && exp1 == "" {
		return "", errors.New("declared hashes did not contain supported sha256 or sha1")
	}

	if exp256 != "" && cachedSHA256 != "" && exp1 == "" {
		if !strings.EqualFold(cachedSHA256, exp256) {
			return "", fmt.Errorf("SHA256 mismatch: got %s, want %s", cachedSHA256, exp256)
		}
		return cachedSHA256, nil
	}

	sha256Hex, sha1Hex, err := fileDigests(path, exp256 != "" || cachedSHA256 == "", exp1 != "")
	if err != nil {
		return "", err
	}
	if exp256 != "" {
		if !strings.EqualFold(sha256Hex, exp256) {
			return "", fmt.Errorf("SHA256 mismatch: got %s, want %s", sha256Hex, exp256)
		}
	}
	if exp1 != "" {
		if !strings.EqualFold(sha1Hex, exp1) {
			return "", fmt.Errorf("SHA1 mismatch: got %s, want %s", sha1Hex, exp1)
		}
	}
	if sha256Hex == "" && cachedSHA256 != "" {
		sha256Hex = cachedSHA256
	}
	return sha256Hex, nil
}

func fileDigests(path string, needSHA256, needSHA1 bool) (sha256Hex string, sha1Hex string, err error) {
	if !needSHA256 && !needSHA1 {
		needSHA256 = true
	}
	f, err := os.Open(path)
	if err != nil {
		return "", "", err
	}
	defer f.Close()

	var writers []io.Writer
	var h256, h1 hash.Hash
	if needSHA256 {
		h256 = sha256.New()
		writers = append(writers, h256)
	}
	if needSHA1 {
		h1 = sha1.New()
		writers = append(writers, h1)
	}
	w := io.MultiWriter(writers...)
	if _, err := io.Copy(w, f); err != nil {
		return "", "", err
	}
	if needSHA256 {
		sha256Hex = hex.EncodeToString(h256.Sum(nil))
	}
	if needSHA1 {
		sha1Hex = hex.EncodeToString(h1.Sum(nil))
	}
	return sha256Hex, sha1Hex, nil
}

const maxZipEntrySize = 10 << 20 // 10 MiB limit on metadata entries to prevent zip bomb OOM

func readZipEntry(z *zip.Reader, name string) ([]byte, error) {
	for _, f := range z.File {
		if f.Name != name {
			continue
		}
		r, err := f.Open()
		if err != nil {
			return nil, err
		}
		defer r.Close()
		lr := io.LimitReader(r, maxZipEntrySize+1)
		data, err := io.ReadAll(lr)
		if err != nil {
			return nil, err
		}
		if len(data) > maxZipEntrySize {
			return nil, fmt.Errorf("zip entry %s exceeds maximum allowed size (%d bytes)", name, maxZipEntrySize)
		}
		return data, nil
	}
	return nil, fmt.Errorf("missing zip entry %s", name)
}
