package bootstrap

import (
	"fmt"
	"path/filepath"
	"slices"
	"strings"

	"github.com/mclucy/lucy/document"
	serverpkg "github.com/mclucy/lucy/server"
)

// OutputPolicy defines the lifecycle and ownership of an output file.
type OutputPolicy string

const (
	// PolicyManaged designates outputs that Lucy owns, manages, and protects
	// against local user modifications.
	PolicyManaged OutputPolicy = "managed"
	// PolicySeed designates output files initialized only when missing;
	// subsequent content is user-owned and never clobbered or pruned.
	PolicySeed OutputPolicy = "seed"
	// PolicyDiscard designates outputs generated in staging for execution
	// purposes that must never be committed to the workspace runtime.
	PolicyDiscard OutputPolicy = "discard"
)

// MaterialRole defines the operational purpose of input or staging material.
type MaterialRole string

const (
	// RoleRuntime designates material intended for runtime execution.
	RoleRuntime MaterialRole = "runtime"
	// RoleBootstrapOnly designates material required only during installation
	// or bootstrap execution, not to be retained in runtime output.
	RoleBootstrapOnly MaterialRole = "bootstrap-only"
)

// OutputOrigin indicates whether an output is generated by the bootstrap adapter
// or supplied as a locked input.
type OutputOrigin string

const (
	// OriginGenerated designates outputs generated or extracted by bootstrap execution.
	OriginGenerated OutputOrigin = "generated"
	// OriginInput designates inputs supplied from locked artifacts.
	OriginInput OutputOrigin = "input"
)

// OutputSpec describes a declared exact output path or bounded directory scope.
type OutputSpec struct {
	// Path is the server-relative exact path (if exact).
	Path string
	// Scope is the server-relative bounded directory prefix (if dynamic).
	Scope string
	// Policy is the ownership policy for matching files.
	Policy OutputPolicy
	// Role is the material role for matching files.
	Role MaterialRole
	// Origin indicates whether the path originates from a locked input or generated output.
	Origin OutputOrigin
}

// stageOnly reports whether the declared material exists only to drive staged
// bootstrap execution. Such material is pinned and verified before execution
// but is discarded from the committed runtime tree.
func (s OutputSpec) stageOnly() bool {
	return s.Policy == PolicyDiscard || s.Role == RoleBootstrapOnly
}

// Output describes a concrete staged or verified output file.
type Output struct {
	// Path is the workspace-relative path (e.g. "server.jar" or "server/server.jar").
	Path string
	// ServerPath is the server-relative path (e.g. "server.jar").
	ServerPath string
	// SHA256 is the hexadecimal SHA-256 digest of the file contents.
	SHA256 string
	// Mode is the file permission bits.
	Mode uint32
	// Policy is the ownership policy (managed, seed, discard).
	Policy OutputPolicy
	// Role is the material role (runtime, bootstrap-only).
	Role MaterialRole
}

// CurrentnessStatus indicates whether an existing server tree satisfies the locked bootstrap contract.
type CurrentnessStatus string

const (
	// CurrentnessCurrent indicates all required outputs exist, launcher semantics match,
	// and all locked artifact hashes match.
	CurrentnessCurrent CurrentnessStatus = "current"
	// CurrentnessInconclusive indicates the existing tree cannot be proven to satisfy
	// the locked contract without executing bootstrap.
	CurrentnessInconclusive CurrentnessStatus = "inconclusive"
	// CurrentnessMismatch indicates a missing required output or artifact hash mismatch.
	CurrentnessMismatch CurrentnessStatus = "mismatch"
)

// CheckResult reports the outcome of verifying an existing tree against a locked server.
type CheckResult struct {
	Current bool
	Status  CurrentnessStatus
	Reason  string
	Outputs []Output
}

// validateContract checks the locked server's bootstrap method, locked inputs, and declared outputs.
// It detects and rejects:
// - Unsupported bootstrap adapters.
// - Collisions where a locked input claims an exact path that the method generates (e.g. Fabric input run.sh).
// - Collisions where multiple locked inputs claim the same destination.
// - Overlaps where an exact input or output conflicts with a scope policy (e.g. Forge input in .bootstrap-data/ claiming managed).
// - Overlaps between scopes with conflicting policies or roles.
func validateContract(locked document.LockedServer) (map[string]OutputSpec, []OutputSpec, error) {
	var generated []OutputSpec
	var scopes []OutputSpec

	switch locked.Bootstrapper {
	case serverpkg.BootstrapMethodPlain:
		generated = []OutputSpec{
			{Path: "server.jar", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
		}
	case serverpkg.BootstrapMethodPaperclip:
		generated = []OutputSpec{
			{Path: "server.jar", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
		}
		scopes = []OutputSpec{
			{Scope: "versions/", Policy: PolicyManaged, Role: RoleRuntime},
			{Scope: "libraries/", Policy: PolicyManaged, Role: RoleRuntime},
			{Scope: "cache/", Policy: PolicyManaged, Role: RoleRuntime},
		}
	case serverpkg.BootstrapMethodFabric:
		loaderPath, err := fabricLoaderPath(locked.CoreVersion.String())
		if err != nil {
			return nil, nil, fmt.Errorf("resolving Fabric loader path: %w", err)
		}
		generated = []OutputSpec{
			{Path: "run.sh", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "run.bat", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "fabric-server-launch.jar", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "fabric-server-launcher.properties", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: loaderPath, Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
		}
		scopes = []OutputSpec{
			{Scope: "libraries/", Policy: PolicyManaged, Role: RoleRuntime},
		}
	case serverpkg.BootstrapMethodQuilt:
		loaderPath, err := quiltLoaderPath(locked.CoreVersion.String())
		if err != nil {
			return nil, nil, fmt.Errorf("resolving Quilt loader path: %w", err)
		}
		generated = []OutputSpec{
			{Path: "quilt-server-launch.jar", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "quilt-server-launcher.properties", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: loaderPath, Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
		}
		scopes = []OutputSpec{
			{Scope: "libraries/", Policy: PolicyManaged, Role: RoleRuntime},
		}
	case serverpkg.BootstrapMethodForgeInstaller:
		generated = []OutputSpec{
			{Path: "run.sh", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "run.bat", Policy: PolicyManaged, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "user_jvm_args.txt", Policy: PolicySeed, Role: RoleRuntime, Origin: OriginGenerated},
			{Path: "README.txt", Policy: PolicySeed, Role: RoleRuntime, Origin: OriginGenerated},
		}
		scopes = []OutputSpec{
			{Scope: ".bootstrap-data/", Policy: PolicyDiscard, Role: RoleBootstrapOnly},
			{Scope: "libraries/", Policy: PolicyManaged, Role: RoleRuntime},
		}
	default:
		return nil, nil, fmt.Errorf("unsupported bootstrap adapter %q", locked.Bootstrapper)
	}

	for i := range scopes {
		sc := filepath.ToSlash(filepath.Clean(scopes[i].Scope))
		if !strings.HasSuffix(sc, "/") {
			sc += "/"
		}
		scopes[i].Scope = sc
	}

	genMap := make(map[string]OutputSpec, len(generated))
	for _, gen := range generated {
		clean := filepath.ToSlash(filepath.Clean(gen.Path))
		gen.Path = clean
		genMap[clean] = gen
	}

	exact := make(map[string]OutputSpec, len(generated)+len(locked.Inputs))
	for k, v := range genMap {
		exact[k] = v
	}

	seenInputs := make(map[string]bool, len(locked.Inputs))
	for _, input := range locked.Inputs {
		if err := document.SafeRelativePath(input.Path); err != nil {
			return nil, nil, fmt.Errorf("unsafe locked input path %q: %w", input.Path, err)
		}
		clean := filepath.ToSlash(filepath.Clean(input.Path))
		if seenInputs[clean] {
			return nil, nil, fmt.Errorf("duplicate locked input destination %q", clean)
		}
		seenInputs[clean] = true

		// An independent origin collision fails even when the policies agree.
		if gen, ok := genMap[clean]; ok {
			return nil, nil, fmt.Errorf("collision between locked input and generated bootstrap output claiming %q (input policy %s vs generated policy %s)", clean, PolicyManaged, gen.Policy)
		}

		policy := PolicyManaged
		role := RoleRuntime

		if locked.Bootstrapper == serverpkg.BootstrapMethodForgeInstaller {
			if isForgeDiscardInput(clean) {
				policy = PolicyDiscard
				role = RoleBootstrapOnly
			}
		}

		for _, sc := range scopes {
			if strings.HasPrefix(clean, sc.Scope) {
				if policy != sc.Policy || role != sc.Role {
					return nil, nil, fmt.Errorf("locked input %q (%s/%s) conflicts with bootstrap scope %q (%s/%s)", clean, policy, role, sc.Scope, sc.Policy, sc.Role)
				}
			}
		}

		exact[clean] = OutputSpec{
			Path:   clean,
			Policy: policy,
			Role:   role,
			Origin: OriginInput,
		}
	}

	for _, gen := range genMap {
		for _, sc := range scopes {
			if strings.HasPrefix(gen.Path, sc.Scope) {
				if gen.Policy != sc.Policy || gen.Role != sc.Role {
					return nil, nil, fmt.Errorf("generated output %q (%s/%s) conflicts with bootstrap scope %q (%s/%s)", gen.Path, gen.Policy, gen.Role, sc.Scope, sc.Policy, sc.Role)
				}
			}
		}
	}

	for i := range scopes {
		for j := i + 1; j < len(scopes); j++ {
			s1 := scopes[i]
			s2 := scopes[j]
			if strings.HasPrefix(s1.Scope, s2.Scope) || strings.HasPrefix(s2.Scope, s1.Scope) {
				if s1.Policy != s2.Policy || s1.Role != s2.Role {
					return nil, nil, fmt.Errorf("conflicting overlapping bootstrap scopes: %q (%s/%s) vs %q (%s/%s)", s1.Scope, s1.Policy, s1.Role, s2.Scope, s2.Policy, s2.Role)
				}
			}
		}
	}

	return exact, scopes, nil
}

// OutputSpecs reports the declared output paths and bounded scopes of a locked server.
func OutputSpecs(locked document.LockedServer) []OutputSpec {
	exact, scopes, err := validateContract(locked)
	if err != nil {
		return nil
	}
	specs := make([]OutputSpec, 0, len(exact)+len(scopes))
	for _, spec := range exact {
		specs = append(specs, spec)
	}
	specs = append(specs, scopes...)
	slices.SortFunc(specs, func(a, b OutputSpec) int {
		if a.Path != "" && b.Path != "" {
			return strings.Compare(a.Path, b.Path)
		}
		if a.Path != "" {
			return -1
		}
		if b.Path != "" {
			return 1
		}
		return strings.Compare(a.Scope, b.Scope)
	})
	return specs
}
